import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolvePiRoot } from './test-support.mjs';
const root = resolvePiRoot(), require = createRequire(root + '/package.json');
const { createJiti } = require('jiti');
const jiti = createJiti(import.meta.url, { alias: { '@earendil-works/pi-coding-agent': root + '/dist/index.js', '@earendil-works/pi-tui': require.resolve('@earendil-works/pi-tui'), typebox: require.resolve('typebox') } });
const { AskBox, registerAsk } = await jiti.import('./ask.ts');
const { visibleWidth } = await import(require.resolve('@earendil-works/pi-tui'));
const theme = { fg: (_color, text) => text };
const keys = { matches: (data, action) => ({ 'tui.select.up': '\x1b[A', 'tui.select.down': '\x1b[B', 'tui.select.confirm': '\r', 'tui.select.cancel': '\x1b' })[action] === data };
const tui = { requestRender() {} };
const params = { question: 'What should happen?', context: '日本語 context for a question', options: ['Keep data', 'Delete data'] };
let answer;
const make = () => new AskBox(params, tui, theme, keys, value => { answer = value; });
let box = make();
for (const width of [0, 1, 2, 3, 4, 5, 10, 40, 80, 120]) for (const line of box.render(width)) assert.ok(visibleWidth(line) <= width, `overflow ${width}`);
assert.strictEqual(box.render(120), box.render(120));
box.invalidate();
const before = box.render(80);
const first = before.find(line => line.includes('Keep data'));
const second = before.find(line => line.includes('Delete data'));
assert.ok(first.includes('▸ (*)  Keep data'));
assert.ok(second.includes('  ( )  Delete data'));
assert.equal(visibleWidth(first.slice(0, first.indexOf('Keep data'))), visibleWidth(second.slice(0, second.indexOf('Delete data'))));
assert.equal(first.indexOf('('), second.indexOf('('));
box.handleInput('\x1b[B');
const after = box.render(80);
assert.ok(after.find(line => line.includes('Keep data')).includes('( )'));
assert.ok(after.find(line => line.includes('Delete data')).includes('▸ (*)'));
box.handleInput('\r');
assert.deepEqual(answer, { status: 'answered', answer: 'Delete data', custom: false, index: 1 });
box.handleInput('\x1b'); assert.equal(answer.status, 'answered');
box = make(); box.handleInput('\x1b'); assert.deepEqual(answer, { status: 'cancelled', answer: null });
box = make(); box.focused = true;
box.handleInput('\x1b[B'); box.handleInput('\x1b[B'); box.handleInput('\r');
answer = undefined;
box.handleInput('\r'); assert.equal(answer, undefined, 'blank custom answer submitted');
box.handleInput('A custom answer');
for (const width of [5, 10, 40, 80]) for (const line of box.render(width)) assert.ok(visibleWidth(line) <= width);
box.handleInput('\r');
assert.equal(answer.answer, 'A custom answer'); assert.equal(answer.custom, true);
box = make(); box.handleInput('\x1b[B'); box.handleInput('\x1b[B'); box.handleInput('\r'); box.handleInput('\x1b'); assert.equal(answer.status, 'cancelled');
let tool;
registerAsk({ registerTool: value => { tool = value; } }, () => true, () => 1);
assert.equal(tool.name, 'ask_user');
let result = await tool.execute('test', params, undefined, undefined, { mode: 'rpc' });
assert.equal(result.details.status, 'unavailable');
result = await tool.execute('test', params, AbortSignal.abort(), undefined, { mode: 'tui' });
assert.equal(result.details.status, 'cancelled');
const controller = new AbortController();
result = await tool.execute('test', params, controller.signal, undefined, { mode: 'tui', ui: { custom: async (factory, options) => {
 assert.equal(options.blocked.kind, 'question');
 return await new Promise(done => { factory(tui, theme, keys, done); controller.abort(); });
} } });
assert.equal(result.details.status, 'cancelled');
result = await tool.execute('test', params, undefined, undefined, { mode: 'tui', ui: { custom: async factory => await new Promise(done => { const component = factory(tui, theme, keys, done); component.handleInput('\r'); }) } });
assert.equal(result.details.answer, 'Keep data');
console.log('PASS: Ask box choices, Other input, cancellation/abort, non-TUI safety, blocked status, cache and Unicode resize widths');
