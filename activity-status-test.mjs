import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolvePiRoot } from './test-support.mjs';
const root = resolvePiRoot(), require = createRequire(root + '/package.json');
const jiti = require('jiti').createJiti(import.meta.url, { alias: { '@earendil-works/pi-tui': require.resolve('@earendil-works/pi-tui') } });
const { activityToolLabel, registerActivityStatus } = await jiti.import('./activity-status.ts');
const { visibleWidth } = await import(require.resolve('@earendil-works/pi-tui'));
assert.equal(activityToolLabel('read', { path: '/private/dir/index.ts' }), 'Reading index.ts');
assert.equal(activityToolLabel('edit', { file_path: 'C:\\work\\settings.ts' }), 'Editing settings.ts');
assert.equal(activityToolLabel('write', {}), 'Writing file');
assert.equal(activityToolLabel('bash', { command: '# Run tests\nnpm test --secret KEY' }), 'Run tests');
assert.equal(activityToolLabel('bash', { command: 'npm test --secret KEY' }), 'Running shell command');
assert.equal(activityToolLabel('bash', { command: '#!/bin/bash\nnpm test' }), 'Running shell command');
assert.equal(activityToolLabel('powershell', {}, '\x1b[31mRun\nchecks'), 'Run checks');
assert.ok(visibleWidth(activityToolLabel('read', { path: '列'.repeat(90) })) <= 64);

const events = {}, labels = [];
let enabled = true, showChars = false;
const ctx = { mode: 'tui', ui: { setWorkingMessage: value => labels.push(value) } };
registerActivityStatus({ on: (event, handler) => { events[event] = handler; } }, () => enabled, id => id === 'title' ? 'Verify regression suite' : undefined, () => showChars);
const emit = (type, event = {}, context = ctx) => events[type](event, context);
const start = (id, name, args, parent) => emit('tool_execution_start', { toolCallId: id, toolName: name, args, parentToolCallId: parent });
const end = id => emit('tool_execution_end', { toolCallId: id });
const stream = (type, role = 'assistant', delta = '') => emit('message_update', { message: { role }, assistantMessageEvent: { type, delta } });
const last = () => labels.at(-1);
emit('agent_start', {}, { ...ctx, mode: 'rpc' }); stream('text_delta'); assert.equal(labels.length, 0);
enabled = false; emit('agent_start'); stream('text_delta'); assert.equal(labels.length, 0);
enabled = true;
emit('agent_start'); assert.equal(last(), 'Waiting for model');
stream('thinking_delta'); assert.equal(last(), 'Thinking');
stream('text_delta'); assert.equal(last(), 'Writing reply');
const count = labels.length;
stream('text_delta'); stream('thinking_delta', 'toolResult'); assert.equal(labels.length, count);
emit('message_end', { message: { role: 'assistant', stopReason: 'toolUse' } }); assert.equal(last(), 'Preparing tools');
start('parent', 'codemode'); assert.equal(last(), 'Running tools');
start('one', 'read', { path: '/private/file.ts' }, 'parent'); assert.equal(last(), 'Reading file.ts');
start('title', 'bash', { command: 'private command' }, 'parent'); assert.equal(last(), 'Running 2 tools');
end('one'); assert.equal(last(), 'Verify regression suite');
end('title'); assert.equal(last(), 'Running tools');
end('parent'); assert.equal(last(), 'Waiting for model');
stream('text_delta'); emit('turn_start'); assert.equal(last(), 'Waiting for model');
start('stale', 'bash'); emit('agent_settled', { aborted: true }); assert.equal(last(), undefined);
const cleared = labels.length; end('stale'); stream('text_delta'); assert.equal(labels.length, cleared);
for (const reset of ['session_start', 'session_tree', 'session_shutdown', 'agent_settled']) {
  emit('agent_start'); stream('text_delta'); emit(reset); assert.equal(last(), undefined, reset);
}
showChars = true;
emit('agent_start');
stream('thinking_delta', 'assistant', 'Not visible in the reply');
stream('text_delta', 'assistant', 'Hi 🧪'); assert.equal(last(), 'Writing reply · 4 chars');
stream('text_delta', 'assistant', '\ud83d');
await new Promise(resolve => setTimeout(resolve, 140));
stream('text_delta', 'assistant', '\udca1.'); assert.equal(last(), 'Writing reply · 6 chars');
emit('turn_start'); stream('text_delta', 'assistant', '!'); assert.equal(last(), 'Writing reply · 1 char');
emit('agent_settled'); assert.equal(last(), undefined);
console.log('PASS: optional visible reply characters, Unicode chunk boundaries and turn reset');
console.log('PASS: native activity labels, safe titles, parallel/nested tool counts, streaming deduplication and cleanup');
