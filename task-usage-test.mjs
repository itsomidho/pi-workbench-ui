 const entries = [start, assistant, tool, finish];
 const report = sessionReport(entries);
 assert.equal(report.totals.input, 110);
 assert.equal(report.turns, 1); assert.equal(report.toolCalls, 2); assert.equal(report.elapsedMs, 60000);
 assert.equal(report.byModel.find(m => m.provider === 'provider').totals.input, 100);
 assert.equal(report.byModel.find(m => m.provider === 'unknown').totals.input, 10);
 assert.match(report.warnings.join(' '), /attribution/);
 assert.equal(activeTask(entries), undefined);
 assert.equal(activeTask(entries.slice(0, -1)).id, 'one');
 assert.equal(sessionReport(entries.slice(0, -1), '2026-01-01T00:00:10.000Z').status, 'active');
 assert.throws(() => sessionReport([]), /No task/);
 const incomplete = sessionReport([start, { type: 'message', message: { role: 'assistant', content: [], usage: { input: 0 } } }, finish]);
 assert.equal(incomplete.totals.input, 0); assert.equal(incomplete.totals.output, null);
 assert.match(incomplete.warnings.join(' '), /partial/);
 assert.equal(sessionReport([start, finish]).totals.cost, null);
 // Additional usage entries and branch changes remain in scope only after the marker.
 assert.equal(sessionReport([assistant, start, { type: 'usage', provider: 'p', model: 'm', usage }, { type: 'compaction', usage }, { type: 'branch_summary', usage }, finish]).totals.input, 300);
 assert.equal(sessionReport([...entries, marker('start', '2026-01-01T00:02:00.000Z', 'two')]).totals.input, null);
 const overflow = sessionReport([start, { ...assistant, message: { ...assistant.message, usage: { ...usage, input: Number.MAX_SAFE_INTEGER } } }, assistant, finish]);
 assert.equal(overflow.totals.input, Number.MAX_SAFE_INTEGER); assert.match(overflow.warnings.join(' '), /partial/);
 assert.doesNotMatch(markdown({ ...report, task: '<img src=x> [click](https://invalid)' }), /(?<!\\)<img/);
 const paths = exportReport(report, temp + '/exports');
 assert.equal(statSync(paths[0]).mode & 0o777, 0o600);
 assert.equal(statSync(paths[1]).mode & 0o777, 0o600);
 assert.equal(statSync(temp + '/exports').mode & 0o777, 0o700);
 assert.equal(JSON.parse(readFileSync(paths[0])).totals.input, 110);
 assert.match(readFileSync(paths[1], 'utf8'), /provider\/model/);
 assert.ok(markdown(report).includes('cache read'));
 const taskRoot = temp + '/tasks', dir = taskRoot + '/general/project/task';
 mkdirSync(dir + '/artifacts', { recursive: true });
 writeFileSync(dir + '/artifacts/usage.jsonl', [JSON.stringify({ runId: 'run-a', provider: 'p', model: 'm', usage }), JSON.stringify({ runId: 'run-b', usage }), JSON.stringify({ runId: 'run-a', provider: 'p', model: 'm', usage })].join('\n'));
 const workbench = workbenchReport(dir, 'run-a', taskRoot);
 assert.equal(workbench.totals.input, 200); assert.equal(workbench.turns, 2);
 assert.equal(workbench.toolCalls, null); assert.equal(workbench.elapsedMs, null);
 assert.match(workbench.warnings.join(' '), /duplicate/);
 assert.throws(() => workbenchReport(dir, 'missing', taskRoot), /No usage/);
 assert.throws(() => workbenchReport(temp, 'run-a', taskRoot), /inside/);
 symlinkSync(dir, temp + '/outside-link');
 assert.throws(() => workbenchReport(temp + '/outside-link', 'bad run', taskRoot), /run ID/);
 let command, saved = [], messages = [];
 const pi = { registerCommand: (_name, def) => command = def, appendEntry: (customType, data) => saved.push({ type: 'custom', customType, data }) };
 registerTaskUsage(pi);
 const ctx = { isIdle: () => true, sessionManager: { getBranch: () => saved, getSessionFile: () => '/tmp/session' }, ui: { notify: (message, type) => messages.push({ message, type }) } };
 await command.handler('start Busy', { ...ctx, isIdle: () => false }); assert.match(messages.at(-1).message, /Wait/); assert.equal(saved.length, 0);
