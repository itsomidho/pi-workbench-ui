import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolvePiRoot } from './test-support.mjs';
const root = resolvePiRoot(), require = createRequire(root + '/package.json');
const { createJiti } = require('jiti');
const jiti = createJiti(import.meta.url, { alias: { '@earendil-works/pi-coding-agent': root + '/dist/index.js', '@earendil-works/pi-tui': require.resolve('@earendil-works/pi-tui'), typebox: require.resolve('typebox') } });
const { TokenUsageIndex, reportedCounts, formatUsage, registerTokenUsage } = await jiti.import('./token-usage.ts');
const { frame } = await jiti.import('./index.ts');
const { defaults } = await jiti.import('./settings.ts');
const { Text, visibleWidth } = await import(require.resolve('@earendil-works/pi-tui'));
assert.equal(reportedCounts(null), undefined);
assert.equal(reportedCounts({ input: -1, output: NaN }), undefined);
assert.equal(formatUsage(reportedCounts({ input: 0, output: 0 })), '↑0 ↓0');
assert.equal(formatUsage(reportedCounts({ output: 5 })), '↑— ↓5');
assert.equal(formatUsage(undefined), '—');
const message = { role: 'assistant', content: [{ type: 'toolCall', id: 'a' }, { type: 'toolCall', id: 'b' }], usage: { input: 1200, output: 320, cacheRead: 4000, cacheWrite: 200 } };
const index = new TokenUsageIndex();
index.assistant(message);
assert.equal(index.label('a'), 'shared turn: ↑1.2k ↓320 R4.0k W200');
assert.equal(index.label('b'), index.label('a'), 'parallel calls share, not split, provider usage');
assert.equal(index.latest.input, 1200);
index.nested('a/1', 'a');
assert.equal(index.label('a/1'), index.label('a'));
index.result('a', { input: 20, output: 8 });
assert.match(index.label('a'), /tool model: ↑20 ↓8/);
assert.ok(!index.label('b').includes('tool model'));
assert.equal(index.latest.input, 1200, 'tool usage must not alter shared turn usage');
const entries = [{ type: 'message', message }, { type: 'message', message: { role: 'toolResult', toolCallId: 'a', usage: { input: 20, output: 8 } } }];
const restored = new TokenUsageIndex();
restored.restore(entries);
assert.equal(restored.label('a'), index.label('a'));
restored.restore([]);
assert.equal(restored.label('a'), 'shared turn: —', 'tree navigation must clear abandoned branch usage');
assert.equal(restored.hasTurn, false);
index.assistant({ role: 'assistant', content: [{ type: 'toolCall', id: 'missing' }] });
assert.equal(index.label('missing'), 'shared turn: —');
assert.equal(index.latest, undefined, 'missing usage must not reuse previous turn');
index.assistant({ role: 'assistant', content: [], usage: { input: 5, output: 3 } });
assert.equal(index.latest.output, 3, 'text-only turns remain visible');
// Exercise live hooks with fake events but real session shapes.
const handlers = {}, statuses = new Map();
let scans = 0, draws = 0, enabled = true;
const pi = { on(name, fn) { (handlers[name] ??= []).push(fn); } };
const live = registerTokenUsage(pi, () => enabled, () => draws++);
const ctx = { hasUI: true, sessionManager: { getBranch() { scans++; return entries; } }, ui: { setStatus: (key, value) => statuses.set(key, value) } };
const emit = (name, event = {}) => handlers[name]?.forEach(fn => fn(event, ctx));
emit('session_start');
assert.match(statuses.get('workbench-turn-usage'), /turn: ↑1.2k ↓320/);
for (let i = 0; i < 1000; i++) live.label('a');
assert.equal(scans, 1, 'no session scans while rendering tool labels');
emit('message_end', { message });
emit('tool_execution_start', { toolCallId: 'a/1', parentToolCallId: 'a' });
emit('tool_execution_end', { toolCallId: 'a/1', result: { usage: { input: 2, output: 1 } } });
assert.match(live.label('a/1'), /shared turn: ↑1.2k.*tool model: ↑2 ↓1/);
emit('message_end', { message: { role: 'toolResult', toolCallId: 'b', usage: { input: 7, output: 4 } } });
assert.match(live.label('b'), /tool model: ↑7 ↓4/);
enabled = false; emit('session_tree');
assert.equal(statuses.get('workbench-turn-usage'), undefined);
emit('session_shutdown');
assert.equal(live.label('a'), 'shared turn: —');
assert.ok(draws > 0);
// Bottom-right placement on wide terminals; full wrapped label on narrow ones.
let usage = 'shared turn: ↑1.2k ↓320';
const component = frame(new Text('result', 0, 0), 'done', 'bottom', s => s, false, defaults, false, () => usage);
assert.match(component.render(120).at(-1), /shared turn: ↑1.2k ↓320 ──╯$/);
for (const width of [1, 2, 3, 4, 10, 30, 80, 120]) {
 for (const line of component.render(width)) assert.ok(visibleWidth(line) <= width, `overflow ${width}`);
}
assert.ok(component.render(30).join('\n').includes('shared turn:'));
const first = component.render(120);
usage = 'shared turn: —';
assert.notStrictEqual(component.render(120), first);
assert.match(component.render(120).at(-1), /shared turn: —/);
const palette = { accent: 81, success: 114, muted: 245, dim: 242 };
const colorTheme = { fg: (color, text) => `\x1b[38;5;${palette[color]}m${text}\x1b[39m` };
const styled = index.label('a', colorTheme);
assert.ok(styled.includes('\x1b[38;5;81m↑1.2k'));
assert.ok(styled.includes('\x1b[38;5;114m↓320'));
assert.ok(styled.includes('\x1b[38;5;245mR4.0k'));
assert.ok(styled.includes('\x1b[38;5;245mW200'));
assert.ok(index.label('unknown', colorTheme).includes('\x1b[38;5;242m—'));
const styledFrame = frame(new Text('result', 0, 0), 'done', 'bottom', s => `\x1b[90m${s}\x1b[39m`, false, defaults, false, () => styled);
const last = styledFrame.render(160).at(-1);
assert.ok(last.endsWith('\x1b[90m──╯\x1b[39m'), 'restore border color after independently styled token counts');
for (const width of [10, 30, 80, 160]) for (const row of styledFrame.render(width)) assert.ok(visibleWidth(row) <= width);
console.log('PASS: token colors, unavailable/cache styles and border-color isolation');
console.log('PASS: token usage provenance, parallel/nested calls, restoration, unknown/zero/cache usage, event hooks, no render scans and responsive labels');
